function report = summarize(observations,metadata)
%SUMMARIZE Coverage and optional pressure residuals, never a 10 Hz claim.
names={'AIR_TEMP_C','REL_HUMIDITY_PCT','WIND_SPEED_MPS','WIND_FROM_DEG', ...
    'STATION_PRESSURE_HPA','SEA_LEVEL_PRESSURE_HPA'};
dt=seconds(diff(observations.OBSERVATION_TIME));
report=struct('scope','S3 native-cadence observation replay', ...
    'source_type','OFFICIAL_KMA_OBSERVATIONS_NORMALIZED', ...
    'station_id',metadata.station_id,'station_name',metadata.station_name, ...
    'source_url',metadata.source_url,'row_count',height(observations), ...
    'first_timestamp_utc',char(observations.TIMESTAMP_UTC(1)), ...
    'last_timestamp_utc',char(observations.TIMESTAMP_UTC(end)), ...
    'interpolated_rows',0,'applied_10Hz_DSP',false, ...
    'controlled_plunge_test','NOT_APPLICABLE: run_S3 retains the separate synthetic test', ...
    'three_second_gust','NOT_COMPUTED: sparse observations cannot resolve 3 seconds', ...
    'one_minute_telemetry','NOT_EXPORTED: no invented within-minute samples', ...
    'intervals_seconds',unique(dt).', ...
    'regular_cadence',~isempty(dt) && all(dt==dt(1)));
report.median_interval_seconds=NaN;
report.min_interval_seconds=NaN;
report.max_interval_seconds=NaN;
if ~isempty(dt)
    report.median_interval_seconds=median(dt);
    report.min_interval_seconds=min(dt);
    report.max_interval_seconds=max(dt);
end
for k=1:numel(names)
    report.valid_counts.(names{k})=sum(isfinite(observations.(names{k})));
    report.missing_counts.(names{k})=sum(isnan(observations.(names{k})));
end
report.pressure_benchmark=struct('status','NOT_AVAILABLE', ...
    'reason','Requires paired station pressure, published sea-level pressure, and verified pressure sensor elevation.', ...
    'paired_count',0);
hasElevation=isfield(metadata,'pressure_elevation_m') && ...
    isnumeric(metadata.pressure_elevation_m) && isscalar(metadata.pressure_elevation_m) && ...
    isfinite(metadata.pressure_elevation_m) && ...
    isfield(metadata,'pressure_elevation_source_url') && ...
    validText(metadata.pressure_elevation_source_url);
p=observations.STATION_PRESSURE_HPA;
reference=observations.SEA_LEVEL_PRESSURE_HPA;
valid=isfinite(p) & p>0 & isfinite(reference) & reference>0;
if hasElevation && any(valid)
    h=metadata.pressure_elevation_m;
    base=1-0.0065*h/288.15;
    if base<=0, error('songdo:ObservationElevation','Invalid pressure elevation.'); end
    estimated=p(valid)*base^(-9.80665*0.0289644/(8.3144598*0.0065));
    residual=estimated-reference(valid);
    report.pressure_benchmark=struct('status','DESCRIPTIVE_COMPARISON_ONLY', ...
        'reason','Standard-atmosphere estimate versus published KMA reduction; no course pass tolerance supplied.', ...
        'paired_count',sum(valid),'pressure_elevation_m',h, ...
        'elevation_source_url',metadata.pressure_elevation_source_url, ...
        'mean_bias_hpa',mean(residual),'mae_hpa',mean(abs(residual)), ...
        'rmse_hpa',sqrt(mean(residual.^2)),'max_abs_error_hpa',max(abs(residual)));
end
report.limitations={ ...
    'Station identity is the source station, not automatically the S3 virtual station or assignment station 512.', ...
    'CSV/sidecar labels do not themselves authenticate the source; retain raw downloads and provenance.', ...
    'Cadence describes downloaded rows, not the instrument sampling frequency.', ...
    'No PT100 lag-reduction or sensor noise-removal claim follows from these observations.', ...
    'Wind direction is meteorological FROM degrees, retained separately from the synthetic u/v convention.'};
end

function valid = validText(value)
valid=(ischar(value) && isrow(value) && ~isempty(value)) || ...
    (isstring(value) && isscalar(value) && ~ismissing(value) && strlength(value)>0);
end
