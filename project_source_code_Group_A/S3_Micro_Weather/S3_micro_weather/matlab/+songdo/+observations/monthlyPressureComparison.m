function report = monthlyPressureComparison(source)
%MONTHLYPRESSURECOMPARISON Descriptive comparison of monthly pressure means.
% A monthly mean is not a timestamped instantaneous observation.
if ~isstruct(source) || ~isscalar(source)
    error('songdo:MonthlyMetadata','Input must be one source record.');
end
textFields={'station_id','station_name','month','aggregation','source_url', ...
    'pressure_elevation_source_url','pressure_elevation_temporal_status'};
for k=1:numel(textFields)
    key=textFields{k};
    if ~isfield(source,key) || ~validText(source.(key))
        error('songdo:MonthlyMetadata','Missing scalar source text: %s.',key);
    end
end
if isempty(regexp(char(source.month),'^\d{4}-(0[1-9]|1[0-2])$','once')) || ...
        ~strcmp(source.aggregation,'monthly_mean')
    error('songdo:MonthlyInterval','Expected YYYY-MM and monthly_mean aggregation.');
end
numericFields={'station_pressure_hpa','sea_level_pressure_hpa','pressure_elevation_m'};
for k=1:numel(numericFields)
    key=numericFields{k};
    if ~isfield(source,key) || ~isnumeric(source.(key)) || ...
            ~isscalar(source.(key)) || ~isreal(source.(key)) || ~isfinite(source.(key))
        error('songdo:MonthlyValue','Expected one finite numeric value: %s.',key);
    end
end
p=source.station_pressure_hpa; reference=source.sea_level_pressure_hpa;
h=source.pressure_elevation_m;
if p<=0 || reference<=0 || 1-0.0065*h/288.15<=0
    error('songdo:MonthlyValue','Pressure must be positive and elevation physically admissible.');
end
factor=(1-0.0065*h/288.15)^(-9.80665*0.0289644/(8.3144598*0.0065));
estimate=p*factor;
report=struct('scope','S3 alternative monthly pressure consistency comparison', ...
    'status','DESCRIPTIVE_ALTERNATIVE_NOT_EXACT_ASSIGNMENT_STATION', ...
    'station_id',source.station_id,'station_name',source.station_name, ...
    'month',source.month,'aggregation','monthly_mean', ...
    'period_definition','Calendar month in KMA source; not an instantaneous observation', ...
    'source_url',source.source_url, ...
    'station_pressure_mean_hpa',p,'published_sea_level_pressure_mean_hpa',reference, ...
    'pressure_elevation_m',h,'pressure_elevation_source_url',source.pressure_elevation_source_url, ...
    'pressure_elevation_temporal_status',source.pressure_elevation_temporal_status, ...
    'standard_atmosphere_factor',factor,'estimated_sea_level_pressure_mean_hpa',estimate, ...
    'signed_difference_hpa',estimate-reference,'absolute_difference_hpa',abs(estimate-reference), ...
    'acceptance_threshold','NOT_DEFINED','exact_station_512_requirement_satisfied',false, ...
    'constants',struct('L_K_per_m',0.0065,'T0_K',288.15,'g_m_per_s2',9.80665, ...
        'M_kg_per_mol',0.0289644,'R_J_per_mol_K',8.3144598));
if isfield(source,'period_start_kst') && isfield(source,'period_end_exclusive_kst')
    report.period_start_kst=source.period_start_kst;
    report.period_end_exclusive_kst=source.period_end_exclusive_kst;
end
report.limitations={ ...
    'Different station and monthly aggregation: not the exact Songdo station-512 pressure cross-reference.', ...
    ['Pressure-elevation provenance: ' char(source.pressure_elevation_temporal_status)], ...
    'Published monthly means are rounded; discrepancy is descriptive, not measurement error or a pass/fail result.', ...
    'A fixed standard-atmosphere factor is linear in station pressure; KMA operational reduction may use different conditions.', ...
    'No temperature-dependent reduction, instantaneous validation, or fabricated within-month observations are claimed.'};
end

function valid = validText(value)
valid=(ischar(value) && isrow(value) && ~isempty(value)) || ...
    (isstring(value) && isscalar(value) && ~ismissing(value) && strlength(value)>0);
end
