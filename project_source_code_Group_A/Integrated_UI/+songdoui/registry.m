% -------------------------------------------------------------------------
function s = base(code, name, site, id, lat, lon, elev, color)
s = struct('code', code, 'name', name, 'site', site, 'stationId', id, ...
    'lat', lat, 'lon', lon, 'elev', elev, 'color', color, ...
    'folder', '', 'paths', {{}}, 'runner', '', 'script', '', 'entry', '', ...
    'howToRun', '', 'jsonFile', '', 'tasks', []);
end

function t = task(id, title, spec, target, impl, figPatterns, view)
% view: ''        -> show matched member figure(s)
%       'json'    -> show exported telemetry JSON + schema validation
%       'S5-k'    -> crop the subplot whose title contains this tag
%       'missing' -> scenario not implemented in the midterm submission
t = struct('id', id, 'title', title, 'spec', spec, 'target', target, ...
    'impl', impl, 'figPatterns', {figPatterns}, 'view', view, ...
    'implemented', ~strcmp(view, 'missing'));
end
